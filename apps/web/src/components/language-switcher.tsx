function translateElement(element: HTMLElement, language: Language) {
  for (const attribute of ['placeholder', 'title', 'aria-label', 'alt']) {
    const value = element.getAttribute(attribute);
    const translated = value ? translateString(value, language) : undefined;
    if (translated && translated !== value) element.setAttribute(attribute, translated);
  }
}

function translateComposedText(element: HTMLElement, language: Language) {
  if (['INPUT', 'TEXTAREA', 'SELECT', 'OPTION', 'SCRIPT', 'STYLE'].includes(element.tagName)) return;
  const textNodes = Array.from(element.childNodes).filter(node => node.nodeType === Node.TEXT_NODE);
  if (textNodes.length === 0) return;
  const original = textNodes.map(node => node.textContent ?? '').join('');
  const trimmed = original.trim();
  if (!trimmed) return;
  const translated = translateString(trimmed, language);
  if (translated && translated !== trimmed) {
    const leading = original.match(/^\s*/)?.[0] ?? '';
    const trailing = original.match(/\s*$/)?.[0] ?? '';
    textNodes[0].textContent = `${leading}${translated}${trailing}`;
    for (const node of textNodes.slice(1)) node.textContent = '';
  }
}

function applyLanguage(language: Language) {
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : language === 'ja' ? 'ja' : 'en';
  document.querySelectorAll<HTMLElement>('body *').forEach(element => translateComposedText(element, language));
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) translateText(node, language);
  document.querySelectorAll<HTMLElement>('[placeholder],[title],[aria-label],[alt]').forEach(el => translateElement(el, language));
}

export function LanguageSwitcher() {
  const [language, setLanguage] = useState<Language>('zh');
  useEffect(() => {
    const saved = localStorage.getItem('m2v-language');
    const initial: Language = saved === 'en' || saved === 'ja' ? saved : 'zh';
    setLanguage(initial);
    const observer = new MutationObserver(records => {
      for (const record of records) {
        if (record.type === 'characterData') translateText(record.target, initial);
        for (const added of Array.from(record.addedNodes)) {
          if (added.nodeType === Node.TEXT_NODE) translateText(added, initial);
          else if (added instanceof HTMLElement) {
            added.querySelectorAll<HTMLElement>('*').forEach(element => translateComposedText(element, initial));
            translateComposedText(added, initial);
            translateElement(added, initial);
            added.querySelectorAll<HTMLElement>('[placeholder],[title],[aria-label],[alt]').forEach(el => translateElement(el, initial));
            const walker = document.createTreeWalker(added, NodeFilter.SHOW_TEXT);
            let textNode: Node | null;
            while ((textNode = walker.nextNode())) translateText(textNode, initial);
          }
        }
        const changedParent = record.target instanceof HTMLElement ? record.target : record.target.parentElement;
        if (changedParent) {
          translateComposedText(changedParent, initial);
          if (changedParent.parentElement) translateComposedText(changedParent.parentElement, initial);
        }
      }
    });
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
    applyLanguage(initial);
    return () => observer.disconnect();
  }, []);
  function change(value: Language) {
    setLanguage(value);
    localStorage.setItem('m2v-language', value);
    applyLanguage(value);
    // The observer reads the persisted selection for subsequent UI updates.
    window.location.reload();
  }
  return <label className="language-switcher"><span>文A</span><select aria-label="Language" value={language} onChange={event => change(event.target.value as Language)}><option value="zh">中文</option><option value="en">English</option><option value="ja">日本語</option></select></label>;
}
